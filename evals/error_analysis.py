"""Error analysis: charge each failed case to a component, tally, name the biggest cell.

    python -m evals.error_analysis          # writes reports/error_analysis.md

Field-guide rule 12: run error analysis before choosing a fix. For each failed
case, mark the first component that went wrong, tally per component, fix the
biggest cell with the cheapest fix, re-run.

The attribution rule is code, not judgement, so the tally is reproducible:
each failed case is charged to the first component in pipeline order
(pipeline -> normalize -> extract -> reconcile -> check -> safety) that has a
failing check. A case whose extraction was wrong is charged to `extract` even
though the wrong extraction also made the verdict wrong downstream - which is
the whole point of ordering the components.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from order_workflow.evals import COMPONENT_ORDER

from . import tracking

DEFAULT_REPORT = tracking.REPO_ROOT / "evals" / "_artifacts" / "report.json"
DEFAULT_OUT = tracking.REPO_ROOT / "reports" / "error_analysis.md"
DEFAULT_NOTES = tracking.REPO_ROOT / "reports" / "error_analysis_notes.md"

COMPONENT_MEANING = {
    "pipeline": "the run raised before producing a result at all",
    "normalize": "step 1 read the document wrong (text, tables, encoding)",
    "extract": "step 2 produced the wrong order data from a correctly read document",
    "reconcile": "step 3 matched the wrong customer or product, or failed to match a real one",
    "check": "steps 2-3 were right and step 4 reached the wrong verdict or exception",
    "safety": "the order data is right, but an instruction planted in the document was "
              "not surfaced to the human at the confirmation gate",
}


def analyse(report: dict) -> dict:
    results = report["results"]
    failed = [r for r in results if r["status"] == "fail"]
    tally = Counter(r["first_failing_component"] or "unattributed" for r in failed)
    by_component: dict[str, list[dict]] = defaultdict(list)
    for r in failed:
        by_component[r["first_failing_component"] or "unattributed"].append(r)
    biggest = tally.most_common(1)[0] if tally else (None, 0)
    return {
        "results": results,
        "failed": failed,
        "tally": tally,
        "by_component": by_component,
        "biggest": biggest,
    }


def _first_reason(case: dict) -> str:
    """The single failing check that earned the case its component."""
    component = case["first_failing_component"]
    for entry in case.get("failed", []):
        if entry.startswith(f"{component}/"):
            return entry[len(component) + 1:]
    return case.get("failed", ["-"])[0] if case.get("failed") else "-"


def render(analysis: dict, report: dict, run_info: dict | None) -> str:
    results, failed, tally = analysis["results"], analysis["failed"], analysis["tally"]
    graded = [r for r in results if r["status"] in ("pass", "fail")]
    biggest_name, biggest_n = analysis["biggest"]

    lines: list[str] = ["# Error analysis", ""]
    lines.append("Generated by `python -m evals.error_analysis`. Every number is in a "
                 "logged MLflow run.")
    lines.append("")
    if run_info:
        lines.append(f"- Run: `{run_info['run_id']}` (`{run_info.get('run_name', '')}`)")
    lines.append(f"- Suite version {report.get('suite_version', '2')}, "
                 f"{len(results)} cases, {len(graded)} graded, "
                 f"{len(results) - len(graded)} skipped")
    lines.append(f"- Mode: {report.get('mode', 'unknown')}")
    lines.append(f"- {len(failed)} case(s) failed "
                 f"({100 * len(failed) / len(graded):.1f}% of graded)")
    lines.append("")

    lines += [
        "## How each failure was attributed",
        "",
        "Each failed case is charged to the first component in pipeline order that has a "
        "failing check. The rule is code, in `evals/error_analysis.py` and "
        "`COMPONENT_ORDER` in `src/order_workflow/evals.py`, so the tally is reproducible "
        "rather than a judgement call:",
        "",
    ]
    for i, component in enumerate(COMPONENT_ORDER, start=1):
        lines.append(f"{i}. **{component}**: {COMPONENT_MEANING[component]}.")
    lines += [
        "",
        "Ordering matters more than the labels do. A case whose extraction was wrong is "
        "charged to `extract` even though the wrong extraction also produced the wrong "
        "verdict downstream; charging it to `check` would send the next fix to the wrong "
        "place.",
        "",
        "## Tally",
        "",
        "| component | failed cases | share of failures |",
        "|-----------|-------------:|------------------:|",
    ]
    for component in [*COMPONENT_ORDER, "unattributed"]:
        n = tally.get(component, 0)
        if n == 0 and component == "unattributed":
            continue
        share = f"{100 * n / len(failed):.0f}%" if failed else "0%"
        lines.append(f"| {component} | {n} | {share} |")
    lines.append(f"| **total** | **{len(failed)}** | **100%** |")
    lines.append("")

    lines += ["## Failures by category", "",
              "| category | graded | passed | failed | pass rate |",
              "|----------|-------:|-------:|-------:|----------:|"]
    for name, stats in sorted(report["category_scores"].items()):
        lines.append(f"| {name} | {stats['graded']} | {stats['passed']} | "
                     f"{stats['failed']} | {100 * stats['pass_rate']:.1f}% |")
    lines.append("")

    lines += ["## Every failed case", "",
              "| # | case | category | component | the check that earned it |",
              "|--:|------|----------|-----------|--------------------------|"]
    ordered = sorted(
        failed,
        key=lambda r: (COMPONENT_ORDER.index(r["first_failing_component"])
                       if r["first_failing_component"] in COMPONENT_ORDER else 99, r["case"]),
    )
    for i, case in enumerate(ordered, start=1):
        reason = _first_reason(case).replace("|", "/")
        if len(reason) > 110:
            reason = reason[:107] + "..."
        lines.append(f"| {i} | `{case['case']}` | {case['category']} | "
                     f"**{case['first_failing_component']}** | {reason} |")
    lines.append("")

    lines += ["## The biggest cell", ""]
    if biggest_name is None:
        lines.append("No failures. Nothing to attribute.")
    else:
        share = 100 * biggest_n / len(failed)
        lines.append(f"**{biggest_name}**, {biggest_n} of {len(failed)} failed cases "
                     f"({share:.0f}%).")
        lines.append("")
        lines.append(f"{COMPONENT_MEANING[biggest_name].capitalize()}.")
        lines.append("")
        # Group by failure signature. Twenty-five cases failing the same way is
        # one finding, and printing it twenty-five times hides that.
        groups = _group_by_signature(analysis["by_component"][biggest_name])
        for signature, cases in groups:
            lines.append(f"**{len(cases)} case(s)** - {signature}")
            lines.append("")
            for case in cases:
                lines.append(f"- `{case['case']}` ({case['category']})")
            lines.append("")
    return "\n".join(lines)


SIGNATURE_NOISE = re.compile(r"'request_id': '[^']*'|got .*?, want|\d+")


def _group_by_signature(cases: list[dict]) -> list[tuple[str, list[dict]]]:
    """Collapse failures whose reason differs only in case-specific detail."""
    groups: dict[str, list[dict]] = defaultdict(list)
    for case in cases:
        reason = _first_reason(case)
        signature = SIGNATURE_NOISE.sub("...", reason).strip()
        if len(signature) > 160:
            signature = signature[:157] + "..."
        groups[signature].append(case)
    return sorted(groups.items(), key=lambda kv: -len(kv[1]))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="evals.error_analysis", description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument(
        "--notes", type=Path, default=DEFAULT_NOTES,
        help="Markdown fragment appended verbatim: the diagnosis and the chosen fix, "
             "which are judgement and cannot be generated from the tally.",
    )
    args = parser.parse_args(argv)

    if not args.report.is_file():
        print(f"No report at {args.report}. Run `python -m evals.run_mlflow` first.")
        return 1
    report = json.loads(args.report.read_text(encoding="utf-8"))

    # Prefer the id stamped into the report over the "last run" pointer: the
    # report is the thing being analysed, the pointer is only where to look
    # when an older report predates the stamp.
    if report.get("mlflow_run_id"):
        run_info = {"run_id": report["mlflow_run_id"],
                    "run_name": report.get("mlflow_run_name", "")}
    else:
        pointer = tracking.REPO_ROOT / "evals" / "last_run.json"
        run_info = json.loads(pointer.read_text(encoding="utf-8")) if pointer.is_file() else None
        if run_info:
            run_info = {**run_info, "run_name": run_info.get("run_name", "") + " (from pointer)"}

    body = render(analyse(report), report, run_info)
    if args.notes and args.notes.is_file():
        # The hand-written half: what the tally means and what to do about it.
        # Kept in the repo and appended here so `make analysis` reproduces the
        # whole document rather than half of it.
        body += "\n" + args.notes.read_text(encoding="utf-8").lstrip("\n")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(body, encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
